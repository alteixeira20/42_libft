#include "libft.h"
#include <stdlib.h>

char	*ft_strdup(const char *s)
{
	size_t		len_s;
	char		*dest;
	int			i;

	len_s = ft_strlen(s) + 1;
	dest = (char *)malloc(sizeof(char) * len_s);
	if (!dest)
		return (NULL);
	i = 0;
	while (s[i])
	{
		dest[i] = s[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
